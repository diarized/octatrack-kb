"""Regenerate build/inputs/toc.yaml from the Octatrack Notebook PDF.

WHY THIS EXISTS: the PDF's embedded bookmarks are too sparse in the back half
(Effects / MIDI / Arrangements / System chapters have almost no "N.M" bookmarks),
so a bookmark-driven TOC yields a few monster chunks (one 99-page MIDI chunk).
Instead we scan every page's TEXT for "N.M Title" heading lines, which recovers
the true section structure across all 16 chapters (~149 sections).

METHOD / MAGIC:
- Heading regex: a line of the form `N.M Title` (chapter.section + capitalized
  title). Chapter 1-16, section <= 40.
- Monotonic filter: in page order, accept a heading only if (chapter, section)
  strictly increases. This rejects body-text false positives like "1.5 Bar"
  that appear mid-book.
- Page ranges are inclusive and contiguous: each section spans [its page,
  next section's page - 1]; the last ends just before the Index.
- Each chapter's FIRST section is pulled back to include its title page (the
  decorative chapter-title page that sits before the first numbered section),
  using the nearest level-1 bookmark page within 5 pages.

Run:  uv run python build/tools/build_toc.py
Reads:  build/artifacts/oct.pdf      (local copy of the Notebook)
Writes: build/inputs/toc.yaml
"""
from __future__ import annotations
import re
import pathlib
import fitz  # PyMuPDF
import yaml

_ROOT = pathlib.Path(__file__).resolve().parents[2]
_PDF = _ROOT / "build" / "artifacts" / "oct.pdf"
_OUT = _ROOT / "build" / "inputs" / "toc.yaml"

_HEADING = re.compile(r"^\s*(\d{1,2})\.(\d{1,2})\s+([A-Z].{2,70})$")


def _slug(title: str) -> str:
    title = title.lower().strip().rstrip(".")
    return re.sub(r"[^a-z0-9]+", "-", title).strip("-")[:60]


def build_toc(pdf_path: pathlib.Path = _PDF, out_path: pathlib.Path = _OUT) -> list[dict]:
    doc = fitz.open(str(pdf_path))
    n = doc.page_count
    toc = doc.get_toc()

    # Level-1 chapter title bookmarks (text titles, not "N.M"). Some pages are
    # buggy in the source (e.g. Pattern Basics -> p31); only used when close to
    # a chapter's first detected section.
    l1 = [(page, t.strip()) for lvl, t, page in toc
          if lvl == 1 and not re.match(r"^\d+\.\d+", t.strip())]
    index_page = next((page for lvl, t, page in toc
                       if t.strip().lower() == "index"), n + 1)

    found = []
    for i in range(n):
        for line in doc[i].get_text().splitlines():
            m = _HEADING.match(line)
            if m:
                ch, mn = int(m.group(1)), int(m.group(2))
                if 1 <= ch <= 16 and mn <= 40:
                    found.append((i + 1, ch, mn, m.group(3).strip()))

    found.sort(key=lambda r: r[0])
    last = (0, 0)
    secs = []
    for page, ch, mn, title in found:
        if (ch, mn) <= last:   # monotonic filter rejects false positives
            continue
        last = (ch, mn)
        secs.append([page, ch, mn, title])

    first_page_of_chap: dict[int, int] = {}
    for page, ch, mn, title in secs:
        first_page_of_chap.setdefault(ch, page)
    chap_title_page = {}
    for ch, fp in first_page_of_chap.items():
        cand = [p for p, _ in l1 if 0 <= fp - p <= 5]
        chap_title_page[ch] = max(cand) if cand else fp

    sections: list[dict] = []
    ids: dict[str, int] = {}
    for i, (page, ch, mn, title) in enumerate(secs):
        start = page
        if page == first_page_of_chap[ch]:
            start = min(start, chap_title_page[ch])
        end = (secs[i + 1][0] - 1) if i + 1 < len(secs) else (index_page - 1)
        if sections and start <= sections[-1]["pages"][1]:
            sections[-1]["pages"][1] = start - 1
        end = max(end, start)
        sid = _slug(title)
        if sid in ids:
            ids[sid] += 1
            sid = f"{sid}-{ids[sid]}"
        else:
            ids[sid] = 1
        sections.append(dict(id=sid, title=title, chapter=ch,
                             section=f"{ch}.{mn}", pages=[start, end]))

    bad = [s for s in sections if s["pages"][1] < s["pages"][0]]
    gaps = sum(1 for a, b in zip(sections, sections[1:])
               if b["pages"][0] != a["pages"][1] + 1)
    assert not bad, f"bad ranges: {bad}"
    assert gaps == 0, f"non-contiguous boundaries: {gaps}"

    header = (
        "# toc.yaml - authoritative section -> inclusive page-range map.\n"
        "# Generated by build/tools/build_toc.py (scans page-text 'N.M Title'\n"
        "# headings; embedded PDF bookmarks are too sparse in the back half).\n"
        f"# One chunk per numbered section ({len(sections)} sections, all 16 chapters).\n"
        "# Each chapter's first section is pulled back to include its title page.\n"
    )
    out_path.write_text(header + yaml.safe_dump({"sections": sections},
                                                sort_keys=False, allow_unicode=True))
    print(f"wrote {out_path}: {len(sections)} sections, "
          f"pages {sections[0]['pages'][0]}-{sections[-1]['pages'][1]}")
    return sections


if __name__ == "__main__":
    build_toc()
